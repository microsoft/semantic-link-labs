def ui_strings(language):
    """
    Returns the translated user interface text for a language code, keyed by the
    identifiers the widget looks up. English and languages without a translation
    return an empty dictionary, which leaves the English text in place.
    """

    values = _TRANSLATIONS.get(language or "")
    return dict(zip(_KEYS, values)) if values else {}
